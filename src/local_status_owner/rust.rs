use super::*;
use std::fmt::Write;

pub(super) fn render(graph: &Graph, binding: &Binding) -> String {
    let mut out = String::from("// Generated by Oddlang from oddlang-local-status-owner-v1.\n");
    for (constant, value) in [
        ("EXECUTABLE", &binding.executable),
        ("SOCKET_OPTION", &binding.socket_option),
        ("REQUEST", &graph.request.value),
        ("INVALID_REQUEST", &graph.reply.invalid_request),
        ("BOUND", &graph.lifecycle.bound),
        ("STOPPING", &graph.lifecycle.stopping),
        ("IO", &graph.diagnostics.io),
        ("PRIVATE_PARENT", &graph.diagnostics.private_parent),
        ("PATH", &graph.diagnostics.path),
        ("OCCUPIED", &graph.diagnostics.occupied),
        ("INVALID_TRANSITION", &graph.diagnostics.invalid_transition),
        ("CLEANUP", &graph.diagnostics.cleanup),
    ] {
        writeln!(out, "const {constant}: &str = {value:?};").unwrap();
    }
    let Listener {
        maximum_frame_bytes,
        maximum_clients,
        maximum_path_bytes_exclusive,
        read_deadline_ms,
        write_deadline_ms,
        accept_retry_ms,
        ..
    } = graph.listener;
    writeln!(out,
        "const FRAME_LIMIT: u32 = {maximum_frame_bytes};\nconst MAX_CLIENTS: usize = {maximum_clients};\n\
         const MAX_PATH: usize = {maximum_path_bytes_exclusive};\nconst READ_DEADLINE: u64 = {read_deadline_ms};\n\
         const WRITE_DEADLINE: u64 = {write_deadline_ms};\nconst ACCEPT_RETRY: u64 = {accept_retry_ms};"
    ).unwrap();
    out.push_str("const TRANSITIONS: &[(&str, &str)] = &[\n");
    for transition in &graph.lifecycle.transitions {
        writeln!(out, "    ({:?}, {:?}),", transition.from, transition.to).unwrap();
    }
    out.push_str("];\n");
    writeln!(out,
        "\n#[derive(serde::Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct Request {{\n    #[serde(rename = {:?})]\n    action: String,\n}}\n\
         \n#[derive(serde::Serialize)]\nstruct Snapshot {{\n    #[serde(rename = {:?})]\n    phase: &'static str,\n}}\n\
         \n#[derive(serde::Serialize)]\nstruct Reply {{\n    #[serde(rename = {:?})]\n    ok: bool,\n    #[serde(rename = {:?})]\n    result: Option<Snapshot>,\n    #[serde(rename = {:?})]\n    error: Option<&'static str>,\n}}",
        graph.request.key, graph.reply.state, graph.reply.ok, graph.reply.result, graph.reply.error
    ).unwrap();
    out.push_str(include_str!("runtime.rs.in"));
    out
}
