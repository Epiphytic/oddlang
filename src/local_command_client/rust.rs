use super::*;
use std::fmt::Write;

pub(super) fn render(graph: &Graph, entry: &str) -> Result<String, String> {
    let dynamic = graph.request_arguments().next().is_some();
    let minimum = graph.minimum_request_json();
    if minimum.len() > graph.transport.maximum_frame_bytes as usize {
        return Err(if dynamic {
            "minimum request exceeds frame limit"
        } else {
            "constant request exceeds frame limit"
        }
        .into());
    }
    let mut out = String::from("// Generated by Oddlang from oddlang-local-command-client-v1.\n");
    if !dynamic {
        out.push_str(&transport("", "", "REQUEST.len()", "REQUEST.as_bytes()"));
        writeln!(out, "\nconst REQUEST: &str = {minimum:?};").unwrap();
    } else {
        out.push_str(&transport(
            ", request: &[u8]",
            ", request",
            "request.len()",
            "request",
        ));
        render_request(graph, &mut out);
    }
    writeln!(
        out,
        "const FRAME_LIMIT: u32 = {};",
        graph.transport.maximum_frame_bytes
    )
    .unwrap();
    writeln!(
        out,
        "const DEADLINE_MS: u64 = {};",
        graph.transport.deadline_ms
    )
    .unwrap();
    for (name, diagnostic) in [
        ("BINDING", &graph.errors.binding),
        ("IO", &graph.errors.io),
        ("PEER", &graph.errors.peer),
        ("FRAME_SIZE", &graph.errors.frame_size),
        ("FRAME_JSON", &graph.errors.frame_json),
        ("DEADLINE", &graph.errors.deadline),
    ] {
        writeln!(out, "const {name}: Failure = {};", failure(diagnostic)).unwrap();
    }
    if let Some(discovery) = &graph.discovery {
        discovery.render(&mut out);
    }
    replies::render(&graph.response, &mut out);
    let success_field = graph
        .response
        .fields
        .iter()
        .position(|field| field.key == graph.response.success_field);
    write!(out, "\npub fn {entry}(matches: ArgMatches) -> ExitCode {{\n    match run_inner(&matches) {{\n        Ok(code) => ExitCode::from(code),\n        Err(error) => error.report(),\n    }}\n}}\n").unwrap();
    out.push_str("\nfn run_inner(matches: &ArgMatches) -> Result<u8, Failure> {\n");
    for guard in &graph.guards {
        let (condition, rejected) = guard.rust_rejection();
        writeln!(
            out,
            "    if {condition} {{\n        return Err({});\n    }}",
            failure(rejected)
        )
        .unwrap();
    }
    let request_argument = if dynamic {
        out.push_str("    let request = request_body(matches)?;\n");
        ", request.as_bytes()"
    } else {
        ""
    };
    if graph.discovery.is_some() {
        writeln!(out, "    let explicit = matches.try_get_one::<PathBuf>({:?}).map_err(|_| BINDING)?;\n    let path = discover_endpoint(matches, explicit)?;", graph.socket_argument).unwrap();
        writeln!(out, "    let response = perform(&path{request_argument})?;").unwrap();
    } else {
        writeln!(out, "    let path = matches.try_get_one::<PathBuf>({:?}).map_err(|_| BINDING)?.ok_or(BINDING)?;", graph.socket_argument).unwrap();
        writeln!(out, "    let response = perform(path{request_argument})?;").unwrap();
    }
    out.push_str("    let text = serde_json::to_string(&response).map_err(|_| FRAME_JSON)?;\n    writeln!(std::io::stdout().lock(), \"{}\", text).map_err(|_| IO)?;\n");
    writeln!(
        out,
        "    Ok(if response.value_{} {{ {} }} else {{ {} }})\n}}",
        success_field.ok_or("missing response success field")?,
        graph.response.success_exit,
        graph.response.failure_exit
    )
    .unwrap();
    Ok(out)
}

fn transport(parameter: &str, argument: &str, length: &str, bytes: &str) -> String {
    include_str!("transport.rs.in")
        .replace("/*request_parameter*/", parameter)
        .replace("/*request_argument*/", argument)
        .replace("/*request_length*/", length)
        .replace("/*request_bytes*/", bytes)
}

fn render_request(graph: &Graph, out: &mut String) {
    out.push_str("\nfn request_body(matches: &ArgMatches) -> Result<String, Failure> {\n");
    out.push_str("    let mut request = String::from(\"{\");\n");
    for (index, field) in graph.request.iter().enumerate() {
        let delimiter = if index == 0 { "" } else { "," };
        let key = serde_json::Value::String(field.key.clone());
        let prefix = format!("{delimiter}{key}:");
        writeln!(out, "    request.push_str({prefix:?});").unwrap();
        match &field.value {
            Some(value) => {
                let json = value.to_string();
                writeln!(out, "    request.push_str({json:?});").unwrap();
            }
            None => {
                let argument = field.argument.as_ref().expect("validated argument field");
                let id = &argument.id;
                let explicit = format!(
                    r#"filter(|_| matches.value_source({id:?}) == Some(clap::parser::ValueSource::CommandLine))"#
                );
                let get = match argument.kind {
                    RequestArgumentKind::Flag => format!(
                        "matches.try_get_one::<bool>({id:?}).map_err(|_| BINDING)?.{explicit}.copied().unwrap_or(false)"
                    ),
                    RequestArgumentKind::RepeatedString => format!(
                        "matches.try_get_many::<String>({id:?}).map_err(|_| BINDING)?.{explicit}.map(|values| values.collect::<Vec<_>>()).unwrap_or_default()"
                    ),
                    RequestArgumentKind::String => format!(
                        "matches.try_get_one::<String>({id:?}).map_err(|_| BINDING)?.{explicit}.ok_or(BINDING)?"
                    ),
                    RequestArgumentKind::Unsigned64 => format!(
                        "matches.try_get_one::<u64>({id:?}).map_err(|_| BINDING)?.{explicit}.ok_or(BINDING)?"
                    ),
                };
                writeln!(
                    out,
                    "    request.push_str(&serde_json::to_string(&({get})).map_err(|_| FRAME_JSON)?);"
                ).unwrap();
            }
        }
        out.push_str("    if request.len() >= FRAME_LIMIT as usize { return Err(FRAME_SIZE); }\n");
    }
    out.push_str("    request.push('}');\n    Ok(request)\n}\n");
}

pub(super) fn failure(diagnostic: &Diagnostic) -> String {
    format!("Failure({}, {:?})", diagnostic.exit, diagnostic.stderr)
}

impl Guard {
    pub(crate) fn rust_rejection(&self) -> (String, &Diagnostic) {
        match self {
            Guard::FlagFalse { argument, rejected } => (
                format!(
                    "matches.try_get_one::<bool>({argument:?}).map_err(|_| BINDING)?.copied().unwrap_or(false)"
                ),
                rejected,
            ),
            Guard::Absent { argument, rejected } => (
                format!("matches.try_contains_id({argument:?}).map_err(|_| BINDING)?"),
                rejected,
            ),
            Guard::OneOf {
                argument,
                values,
                rejected,
            } => (
                format!(
                    "matches.try_get_one::<String>({argument:?}).map_err(|_| BINDING)?.is_some_and(|value| !{values:?}.contains(&value.as_str()))"
                ),
                rejected,
            ),
            Guard::PathPresent { argument, rejected } => (
                format!(
                    "matches.try_get_one::<PathBuf>({argument:?}).map_err(|_| BINDING)?.is_none()"
                ),
                rejected,
            ),
        }
    }
}
