//! TypeScript projection of plain, copyable choices.
use super::*;
use std::fmt::Write as _;

const TARGET: &str = "oddlang-checked-values-typescript-v1";

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Overlay {
    format: String,
    #[serde(deserialize_with = "unique_map")]
    types: BTreeMap<String, String>,
    #[serde(deserialize_with = "unique_map")]
    variants: BTreeMap<String, String>,
}

pub fn build(graph: &Path, overlay: &Path, output: &Path) -> Result<()> {
    let graph: Graph = json(graph)?;
    let overlay: Overlay = json(overlay)?;
    let source = render(&graph, &overlay)?;
    let obligations = encode(&obligations(&graph))?;
    let lock = encode(&json!({
        "format": "oddlang-checked-values-typescript-lock-v1",
        "domainSha256": digest(&encode(&graph)?),
        "bindingSha256": digest(&encode(&overlay)?),
        "sourceSha256": digest(source.as_bytes()),
        "obligationsSha256": digest(&obligations),
    }))?;
    publish_projection("values.ts", &source, &obligations, &lock, output)
}

fn render(graph: &Graph, overlay: &Overlay) -> Result<String> {
    if graph.format != FORMAT
        || overlay.format != TARGET
        || graph.types.is_empty()
        || !graph.types.keys().eq(overlay.types.keys())
    {
        return Err("TypeScript checked choices require exact graph and name bindings".into());
    }

    let mut ids = BTreeSet::new();
    declare(&mut ids, &graph.id)?;
    let mut types = BTreeSet::new();
    let mut variant_count = 0;
    let mut source = String::from(
        "// Generated by Oddlang from the checked choice graph.\ndeclare const brand: unique symbol;\n",
    );
    for (id, definition) in &graph.types {
        declare(&mut ids, id)?;
        let Definition::Choice {
            cases,
            equality,
            copy: true,
            debug: false,
        } = definition
        else {
            return Err(format!("TypeScript checked choices do not support {id}"));
        };
        let name = &overlay.types[id];
        if cases.is_empty() || !type_symbol(name) || !types.insert(name) {
            return Err(format!(
                "invalid TypeScript choice name or empty case list: {id}"
            ));
        }

        let mut labels = BTreeSet::new();
        let mut variants = Vec::new();
        for case in cases {
            declare(&mut ids, case)?;
            let label = overlay
                .variants
                .get(case)
                .filter(|label| type_symbol(label) && labels.insert(label.as_str()))
                .ok_or_else(|| format!("invalid or missing TypeScript choice case name: {case}"))?;
            variants.push(label.as_str());
        }
        variant_count += variants.len();
        render_choice(&mut source, name, id, &variants, *equality);
    }
    if variant_count != overlay.variants.len() {
        return Err("unused TypeScript choice case binding".into());
    }
    Ok(source)
}

fn render_choice(source: &mut String, name: &str, id: &str, variants: &[&str], equality: Equality) {
    let ordinal = (0..variants.len())
        .map(|value| value.to_string())
        .collect::<Vec<_>>()
        .join(" | ");
    let (capability, comparison) = match equality {
        Equality::None => ("none", None),
        Equality::Partial => ("partial", Some("partialEquals")),
        Equality::Total => ("total", Some("equals")),
    };
    let identity = serde_json::to_string(id).expect("serialize choice identity");
    writeln!(
        source,
        "\nexport type {name} = ({ordinal}) & {{ readonly [brand]: {identity} }};\nexport const {name} = globalThis.Object.freeze({{",
    )
    .unwrap();
    for (index, variant) in variants.iter().enumerate() {
        writeln!(source, "  {variant}: {index} as {name},").unwrap();
    }
    writeln!(source, "  equality: \"{capability}\" as const,").unwrap();
    writeln!(
        source,
        "  ordinal(value: {name}): {ordinal} {{ return value; }},\n  fromOrdinal(value: unknown): {name} | undefined {{\n    switch (value) {{"
    )
    .unwrap();
    for index in 0..variants.len() {
        writeln!(source, "      case {index}: return {index} as {name};").unwrap();
    }
    source.push_str("      default: return undefined;\n    }\n  },\n");
    if let Some(method) = comparison {
        writeln!(
            source,
            "  {method}(left: {name}, right: {name}): boolean {{ return left === right; }},"
        )
        .unwrap();
    }
    source.push_str("});\n");
}
use super::{Definition, FORMAT, Graph, Result, declare};
use crate::{
    native_package::publish,
    wire_schema::{digest, encode, json},
};
use serde_json::json;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

const RUNTIME: &str = r#"
export type FixedBytesId = keyof typeof definitions;
export type FixedBytes<Id extends FixedBytesId> = Readonly<{ id: Id; copyBytes(): Uint8Array }>;

export class FixedBytesError extends Error {
    readonly id: string;

    constructor(id: string) {
        super(id);
        this.name = "FixedBytesError";
        this.id = id;
    }
}

const arrayPrototype = Object.getPrototypeOf(Uint8Array.prototype);
const nativeLength = Object.getOwnPropertyDescriptor(arrayPrototype, "length")!.get!;
const nativeTag = Object.getOwnPropertyDescriptor(arrayPrototype, Symbol.toStringTag)!.get!;

export function fromBytes<Id extends FixedBytesId>(id: Id, input: Uint8Array): FixedBytes<Id> {
    if (typeof id !== "string" || !Object.hasOwn(definitions, id)) {
        throw new RangeError("unknown fixed-byte identity");
    }
    if (nativeTag.call(input) !== "Uint8Array") throw new TypeError("expected a Uint8Array");

    const { length, failure } = definitions[id];
    if (nativeLength.call(input) !== length) throw new FixedBytesError(failure);
    const owned = new Uint8Array(length);
    if (owned.length !== 0) {
        try {
            owned.set(input);
        } catch (error) {
            if (error instanceof RangeError) throw new FixedBytesError(failure);
            throw error;
        }
    }
    return Object.freeze({ id, copyBytes: () => new Uint8Array(owned) });
}
"#;

pub fn build(graph: &Path, output: &Path) -> Result<()> {
    let graph: Graph = json(graph)?;
    if graph.format != FORMAT || graph.types.is_empty() {
        return Err("expected a nonempty checked values graph".into());
    }

    let mut identities = BTreeSet::new();
    let mut failures = BTreeSet::new();
    declare(&mut identities, &graph.id)?;
    let mut definitions = BTreeMap::new();
    let mut obligations = Vec::new();
    for (id, definition) in &graph.types {
        declare(&mut identities, id)?;
        let Definition::FixedBytes {
            length,
            failure,
            on_drop,
        } = definition
        else {
            return Err(format!(
                "TypeScript requires a fixed-byte declaration: {id}"
            ));
        };
        failures.insert(failure);
        definitions.insert(id, json!({ "length": length, "failure": failure }));
        obligations.push(json!({
            "declaration": id,
            "role": "checked-value-domain",
            "expected": {
                "length": length,
                "failure": failure,
                "input": "exact-bytes",
                "ownsInputCopy": true,
                "view": "copy",
                "onDrop": on_drop,
            },
            "qualification": "independent-witness-required",
            "disposal": {
                "qualification": "unsupported",
                "reason": "Node.js provides no deterministic destruction or storage erasure for this value.",
            },
        }));
    }
    for failure in failures {
        declare(&mut identities, failure)?;
    }

    let definitions = serde_json::to_string_pretty(&definitions).map_err(|err| err.to_string())?;
    let source = format!("const definitions = {definitions} as const;\n{RUNTIME}");
    let obligations = encode(&json!({
        "format": FORMAT,
        "domain": graph.id,
        "target": "typescript",
        "obligations": obligations,
    }))?;
    let lock = encode(&json!({
        "format": "oddlang-checked-values-lock-v1",
        "target": "typescript",
        "domainSha256": digest(&encode(&graph)?),
        "sourceSha256": digest(source.as_bytes()),
        "obligationsSha256": digest(&obligations),
    }))?;
    let parent = output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let stage = tempfile::tempdir_in(parent).map_err(|err| err.to_string())?;
    for (name, bytes) in [
        ("values.mts", source.as_bytes()),
        ("obligations.json", &obligations),
        ("projection.lock", &lock),
    ] {
        fs::write(stage.path().join(name), bytes).map_err(|err| err.to_string())?;
    }
    publish(stage.path(), output)
}
