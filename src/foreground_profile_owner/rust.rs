use super::*;
use std::fmt::Write;

pub(super) fn render(graph: &Graph, binding: &Binding) -> String {
    let mut out =
        String::from("// Generated by Oddlang from oddlang-foreground-profile-owner-v1.\n");
    writeln!(
        out,
        "use crate::{} as StatusOwner;",
        binding.status_owner.join("::")
    )
    .unwrap();
    for (name, value) in [
        ("FOREGROUND_ARG", &graph.arguments.foreground),
        ("STATE_ARG", &graph.arguments.state),
        ("IDENTITY_ARG", &graph.arguments.identity),
        ("BACKEND_ARG", &graph.arguments.backend),
        ("ROUTE_ARG", &graph.arguments.route),
        ("RELAY_ARG", &graph.arguments.relay),
        ("ROUTE_VALUE", &graph.activation.route_value),
        ("PROFILE_DOCUMENT", &graph.profile.document),
        ("LEASE_FILE", &graph.profile.lock),
        ("READY", &graph.profile.ready),
        ("BACKEND", &graph.profile.backend),
        ("RUNTIME_PREFIX", &graph.runtime.prefix),
        ("BINDING_FILE", &graph.runtime.binding),
        ("SOCKET_FILE", &graph.runtime.socket),
        ("CREDENTIAL_DIRECTORY", &graph.provider.directory),
        ("SIGNING_PREFIX", &graph.provider.signing_prefix),
        ("DATA_PREFIX", &graph.provider.data_prefix),
    ]
    .into_iter()
    .chain(graph.diagnostics.values())
    {
        writeln!(out, "const {name}: &str = {value:?};").unwrap();
    }
    let choices = graph.arguments.backend_choices.iter().collect::<Vec<_>>();
    writeln!(
        out,
        "const BACKEND_CHOICES: &[(&str, &str)] = &{choices:?};"
    )
    .unwrap();
    for (name, ty, value) in [
        ("PROFILE_FORMAT", "u8", usize::from(graph.profile.format)),
        ("PROFILE_LIMIT", "u32", graph.profile.maximum_bytes as usize),
        ("NAME_LIMIT", "usize", graph.profile.name_limit),
        ("SHORT_ID", "usize", graph.profile.short_reference_bytes),
        (
            "CREDENTIAL_ID",
            "usize",
            graph.profile.credential_reference_bytes,
        ),
        ("RUNTIME_FORMAT", "u8", usize::from(graph.runtime.format)),
        (
            "MAX_PATH",
            "usize",
            graph.runtime.maximum_path_bytes_exclusive,
        ),
        ("RESERVED_PATH", "usize", graph.runtime.reserved_path_bytes),
    ] {
        writeln!(out, "const {name}: {ty} = {value};").unwrap();
    }

    writeln!(
        out,
        "const ACTIVATION_MS: u64 = {};",
        graph.activation.deadline_ms
    )
    .unwrap();
    out.push_str(
        "\n#[derive(serde::Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct ProfileRecord {\n",
    );
    let profile = &graph.profile.fields;
    fields(
        &mut out,
        [
            ("format", "u8", &profile.format),
            ("profile_id", "String", &profile.profile_id),
            ("name", "String", &profile.name),
            ("transaction", "String", &profile.transaction),
            ("phase", "String", &profile.phase),
            ("backend", "String", &profile.backend),
            ("signing_ref", "String", &profile.signing_ref),
            ("data_ref", "String", &profile.data_ref),
            ("device", "String", &profile.device),
            ("public_key", "Option<String>", &profile.public_key),
        ],
    );
    out.push_str("}\n\n#[derive(serde::Deserialize, serde::Serialize, PartialEq, Eq)]\n#[serde(deny_unknown_fields)]\nstruct RuntimeRecord {\n");
    let runtime = &graph.runtime.fields;
    fields(
        &mut out,
        [
            ("format", "u8", &runtime.format),
            ("profile_id", "String", &runtime.profile_id),
            ("root", "std::path::PathBuf", &runtime.root),
        ],
    );
    out.push_str("}\n");
    out.push_str(include_str!("support.rs.in"));
    out.push('\n');
    if let (Some(lifecycle), Some(path)) = (&graph.lifecycle, &binding.retained_stores) {
        render_lifecycle(
            &mut out,
            lifecycle,
            path,
            graph.activation.relay_runtime.as_ref(),
            graph.room_prepare.as_ref(),
            graph.room_submit.as_ref().zip(binding.room_submit.as_ref()),
        );
    } else {
        out.push_str(include_str!("runtime.rs.in"));
    }
    writeln!(
        out,
        r#"
pub fn {}(matches: ArgMatches) -> ExitCode {{
    match run(&matches) {{
        Ok(()) => ExitCode::SUCCESS,
        Err((code, message)) => {{
            let _ = writeln!(io::stderr().lock(), "{{message}}");
            ExitCode::from(code)
        }}
    }}
}}
"#,
        binding.entry
    )
    .unwrap();
    out
}

fn fields<const N: usize>(out: &mut String, fields: [(&str, &str, &String); N]) {
    for (name, ty, wire) in fields {
        writeln!(out, "    #[serde(rename = {wire:?})]\n    {name}: {ty},").unwrap();
    }
}

fn render_lifecycle(
    out: &mut String,
    model: &Lifecycle,
    path: &[String],
    relay: Option<&RelayRuntime>,
    prepare: Option<&RoomPrepare>,
    submit: Option<(&RoomSubmit, &RoomSubmitBinding)>,
) {
    writeln!(out, "use crate::{} as open_stores;", path.join("::")).unwrap();
    writeln!(out, "const SHUTDOWN_MS: u64 = {};", model.shutdown_ms).unwrap();
    writeln!(out, "const DIAL_MS: u64 = {};", model.dial_ms).unwrap();
    writeln!(out, "const DIAL_ATTEMPTS: u8 = {};", model.dial_attempts).unwrap();
    writeln!(out, "const REPORT_VERSION: u8 = {};", model.report_version).unwrap();
    writeln!(
        out,
        "const PROVIDER_OPEN_FAILURE: &str = {:?};",
        model.provider_open_failure
    )
    .unwrap();
    writeln!(
        out,
        "const EXCLUDED_OWNER_FILES: &[&str] = &{:?};",
        model.excluded_profile_entries,
    )
    .unwrap();
    let engine_stop = match model.engine {
        EngineRole::Absent => (false, true),
    };
    writeln!(out, "const ENGINE_STOP: (bool, bool) = {engine_stop:?};").unwrap();
    out.push_str("#[derive(serde::Serialize)]\nstruct TerminalReport {\n");
    let names = &model.report_fields;
    fields(
        out,
        [
            ("schema", "u8", &names.schema),
            ("engine_quiesced", "bool", &names.engine_quiesced),
            ("engine_stop_complete", "bool", &names.engine_stop_complete),
            (
                "provider_stop_complete",
                "bool",
                &names.provider_stop_complete,
            ),
            (
                "runtime_cleanup_complete",
                "bool",
                &names.runtime_cleanup_complete,
            ),
        ],
    );
    out.push_str("}\n");
    if let Some(relay) = relay {
        writeln!(
            out,
            "const RELAY_STATE: &str = {:?};",
            relay.state_directory
        )
        .unwrap();
        writeln!(
            out,
            "const RELAY_CACHE: &str = {:?};",
            relay.cache_directory
        )
        .unwrap();
        writeln!(
            out,
            "const RELAY_FRAME_LIMIT: usize = {};",
            relay.maximum_frame_bytes
        )
        .unwrap();
        writeln!(out, "const PROVIDER_READY: &str = {:?};", relay.ready_state).unwrap();
        writeln!(
            out,
            "const RELAY_HEALTH_MS: u64 = {};",
            relay.health_check_ms
        )
        .unwrap();
        writeln!(
            out,
            "const APPLICATION_COMPONENTS: &[u16] = &{:?};",
            relay.application_components
        )
        .unwrap();
        out.push_str(include_str!("checked_relay_sink.rs.in"));
        out.push_str(include_str!("onion_transport.rs.in"));
        out.push_str(include_str!("key_package.rs.in"));
        let lifecycle = include_str!("active_lifecycle.rs.in");
        if let Some(prepare) = prepare {
            render_room_prepare(out, prepare, submit);
            let patches = [
                (
                    "    storage_closer: storage_sqlite::DatabaseCloser,",
                    "    storage_closer: storage_sqlite::DatabaseCloser,\n    room_storage: storage_sqlite::SqliteAccountStorage,",
                ),
                (
                    "let storage_closer = storage.closer();",
                    "let storage_closer = storage.closer();\n        let room_storage = storage.clone();",
                ),
                (
                    "Ok(Self { runtime, journal, storage_closer, identity,",
                    "Ok(Self { runtime, journal, storage_closer, room_storage, identity,",
                ),
                (
                    "let Self { runtime, journal, storage_closer, identity,",
                    "let Self { runtime, journal, storage_closer, room_storage, identity,",
                ),
                (
                    "        drop(runtime);",
                    "        drop(runtime);\n        drop(room_storage);",
                ),
                (
                    "let routing = StaticTransportRouting::new(vec![endpoint.clone()]);",
                    "let routing = room_routing(root, profile, &endpoint).map_err(|failure| (1, failure))?;",
                ),
                (
                    "let mut activation_failure = None;",
                    "let mut activation_failure = None;\n    let (prepare, mut pending) = RoomPrepareQueue::open(root, profile, &providers)?;",
                ),
                (
                    "owner.serve_until(async {",
                    "owner.serve_routed_until(async {",
                ),
                (
                    "error = providers.transport_lost(&relay) => activation_failure = Some(error),",
                    "error = prepare_active(&mut providers, &relay, &mut pending, &prepare) => activation_failure = Some(error),",
                ),
                (
                    "}).await.map_err(|_| CLEANUP)",
                    "}, { let prepare = prepare.clone(); move |body| prepare.route(body) }).await.map_err(|_| CLEANUP)",
                ),
            ];
            let mut routed_lifecycle = lifecycle.to_owned();
            for (anchor, replacement) in patches {
                assert_eq!(
                    routed_lifecycle.matches(anchor).count(),
                    1,
                    "room preparation template anchor"
                );
                routed_lifecycle = routed_lifecycle.replacen(anchor, replacement, 1);
            }
            if submit.is_some() {
                let patches = [
                    (
                        "let (prepare, mut pending) = RoomPrepareQueue::open(root, profile, &providers)?;",
                        "let (prepare, mut pending) = RoomPrepareQueue::open(root, profile, &providers)?;\n    let (submit, mut submissions) = mpsc::channel(ROOM_SLOT_LIMIT);",
                    ),
                    (
                        "owner.serve_routed_until(async {",
                        "owner.serve_async_routed_until(async {",
                    ),
                    (
                        "prepare_active(&mut providers, &relay, &mut pending, &prepare)",
                        "prepare_active(&mut providers, &relay, &mut pending, &prepare, &mut submissions, &profile.name)",
                    ),
                    (
                        "{ let prepare = prepare.clone(); move |body| prepare.route(body) }",
                        "{ let prepare = prepare.clone(); move |body| route_room_request(body, prepare.clone(), submit.clone()) }",
                    ),
                ];
                for (anchor, replacement) in patches {
                    assert_eq!(
                        routed_lifecycle.matches(anchor).count(),
                        1,
                        "submit lifecycle anchor"
                    );
                    routed_lifecycle = routed_lifecycle.replacen(anchor, replacement, 1);
                }
            }
            out.push_str(&routed_lifecycle);
        } else {
            out.push_str(lifecycle);
        }
    } else {
        out.push_str(include_str!("lifecycle.rs.in"));
    }
    out.push_str(include_str!("shutdown.rs.in"));
}

fn render_room_prepare(
    out: &mut String,
    prepare: &RoomPrepare,
    submit: Option<(&RoomSubmit, &RoomSubmitBinding)>,
) {
    for (name, value) in [
        ("ROOM_CONFIGURATION", &prepare.configuration),
        ("PREPARE_OPERATION", &prepare.operation),
        ("ROOM_NAME_PREFIX", &prepare.name_prefix),
        ("ROOM_DESCRIPTION", &prepare.description),
    ] {
        writeln!(out, "const {name}: &str = {value:?};").unwrap();
    }
    for (name, values) in [
        ("PREPARE_REPLY", &prepare.reply[..]),
        ("PREPARE_STATES", &prepare.states[..]),
        ("PREPARE_CATEGORIES", &prepare.categories[..]),
        ("ROOM_ROLES", &prepare.roles[..]),
    ] {
        writeln!(out, "const {name}: &[&str] = &{values:?};").unwrap();
    }
    writeln!(
        out,
        "const ROOM_CONFIG_LIMIT: usize = {};",
        prepare.maximum_config_bytes
    )
    .unwrap();
    writeln!(out, "const ROOM_DEADLINE: u64 = {};", prepare.deadline_ms).unwrap();
    writeln!(
        out,
        "const ROOM_SLOT_LIMIT: usize = {};",
        prepare.slot_limit
    )
    .unwrap();
    out.push_str(
        "#[derive(serde::Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct PrepareRequest {\n",
    );
    fields(
        out,
        [
            ("operation", "String", &prepare.request[0]),
            ("remote", "String", &prepare.request[1]),
            ("relays", "Vec<String>", &prepare.request[2]),
        ],
    );
    out.push_str("}\n#[derive(serde::Deserialize)]\nstruct RoomConfig {\n");
    fields(
        out,
        [
            ("role", "String", &prepare.config_fields[0]),
            ("trust", "Vec<String>", &prepare.config_fields[1]),
            ("relays", "Vec<String>", &prepare.config_fields[2]),
            ("route", "String", &prepare.config_fields[3]),
        ],
    );
    if let Some(lists) = &prepare.restriction_lists {
        writeln!(
            out,
            "    #[serde(rename = {:?})]\n    command_policy: CommandRestrictions,",
            lists.policy_field()
        )
        .unwrap();
    }
    out.push_str("}\n");
    let validate_restrictions = if let Some(lists) = &prepare.restriction_lists {
        lists.render(out);
        "    config.command_policy.validate_bounds().map_err(|_| INVALID_PROFILE)?;\n"
    } else {
        ""
    };
    let template = include_str!("room_prepare.rs.in")
        .replace("/*VALIDATE_COMMAND_RESTRICTIONS*/", validate_restrictions);
    if let Some((model, binding)) = submit {
        let signature = "    queue: &RoomPrepareQueue,\n) -> Failure {";
        let request = "            request = pending.recv()";
        assert_eq!(
            template.matches(signature).count(),
            1,
            "submit queue signature"
        );
        assert_eq!(template.matches(request).count(), 1, "submit queue route");
        out.push_str(&template
            .replacen(signature,
                "    queue: &RoomPrepareQueue,\n    submissions: &mut mpsc::Receiver<QueuedSubmit>,\n    profile: &str,\n) -> Failure {", 1)
            .replacen(request,
                "            submission = submissions.recv() => {\n                let Some((request, reply)) = submission else { return IO; };\n                if !reply.is_closed() {\n                    let result = commit_room_submit(providers, queue, &request, profile);\n                    let _ = reply.send(result);\n                }\n                continue;\n            }\n            request = pending.recv()", 1));
        render_room_submit(out, prepare, model, binding);
    } else {
        out.push_str(&template);
    }
}

fn render_room_submit(
    out: &mut String,
    prepare: &RoomPrepare,
    model: &RoomSubmit,
    binding: &RoomSubmitBinding,
) {
    writeln!(
        out,
        "\nuse crate::{} as SubmitQueue;",
        binding.queue.join("::")
    )
    .unwrap();
    writeln!(
        out,
        "use crate::{} as SubmitWire;",
        binding.request_type.join("::")
    )
    .unwrap();
    writeln!(
        out,
        "use crate::{} as encode_submit_wire;",
        binding.encode.join("::")
    )
    .unwrap();
    writeln!(out, "const SUBMIT_OPERATION: &str = {:?};", model.operation).unwrap();
    writeln!(out, "const SUBMIT_QUEUED: &str = {:?};", model.queued).unwrap();
    writeln!(
        out,
        "const SUBMIT_ACCEPTED_OK: bool = {};",
        model.accepted_ok
    )
    .unwrap();
    writeln!(out, "const SUBMIT_REFUSED_OK: bool = {};", model.refused_ok).unwrap();
    writeln!(
        out,
        "const SUBMIT_HANDLE_FORMAT: u8 = {};",
        model.handle_format
    )
    .unwrap();
    writeln!(
        out,
        "const SUBMIT_FAILURES: &[&str] = &{:?};",
        model.failures
    )
    .unwrap();
    writeln!(
        out,
        "const SUBMIT_FUTURE: u64 = {};",
        model.max_future_seconds
    )
    .unwrap();

    out.push_str(
        "#[derive(serde::Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct SubmitRequest {\n",
    );
    fields(
        out,
        [
            ("operation", "String", &model.request[0]),
            ("remote", "String", &model.request[1]),
            ("relays", "Vec<String>", &model.request[2]),
            ("session", "String", &model.request[3]),
            ("request", "String", &model.request[4]),
            ("payload", "SubmitPayload", &model.request[5]),
        ],
    );
    out.push_str(
        "}\n#[derive(serde::Deserialize)]\n#[serde(deny_unknown_fields)]\nstruct SubmitPayload {\n",
    );
    fields(
        out,
        [
            ("chunks", "Vec<String>", &model.payload[0]),
            ("invocation", "String", &model.payload[1]),
            ("bytes", "String", &model.payload[2]),
        ],
    );
    out.push_str("}\n#[derive(serde::Serialize)]\nstruct SubmitReply<T> {\n");
    fields(
        out,
        [
            ("ok", "bool", &prepare.reply[0]),
            ("result", "()", &prepare.reply[1]),
            ("error", "()", &prepare.reply[2]),
            ("command", "T", &prepare.reply[3]),
        ],
    );
    out.push_str("}\n#[derive(serde::Serialize)]\nstruct SubmitAccepted {\n");
    fields(
        out,
        [
            ("state", "&'static str", &prepare.reply[4]),
            ("handle", "SubmitHandle", &model.handle_field),
        ],
    );
    out.push_str("}\n#[derive(serde::Serialize)]\nstruct SubmitRefused {\n");
    fields(
        out,
        [
            ("state", "&'static str", &prepare.reply[4]),
            ("category", "&'static str", &prepare.reply[7]),
            ("handle", "()", &prepare.reply[8]),
        ],
    );
    out.push_str("}\n#[derive(serde::Serialize)]\nstruct SubmitHandle {\n");
    fields(
        out,
        [
            ("format", "u8", &model.handle[0]),
            ("profile", "String", &model.handle[1]),
            ("remote", "String", &model.handle[2]),
            ("session", "String", &model.handle[3]),
            ("invocation", "String", &model.handle[4]),
            ("digest", "String", &model.handle[5]),
        ],
    );
    out.push_str("}\nfn encode_room_submit(\n    local: [u8; 32], remote: [u8; 32], session: [u8; 16], request: [u8; 16],\n    invocation: [u8; 16], chunks: Vec<Vec<u8>>, bytes: Vec<u8>,\n) -> Result<Vec<u8>, Failure> {\n    let value = SubmitWire {\n");
    for (field, value) in binding.fields.iter().zip([
        "local",
        "remote",
        "session",
        "request",
        "invocation",
        "chunks",
        "bytes",
    ]) {
        writeln!(out, "        {field}: {value},").unwrap();
    }
    out.push_str("    };\n    encode_submit_wire(&value).map_err(|_| SUBMIT_FAILURES[0])\n}\n");
    let SubmitIdClock::UnixSecondsU48be = model.id_clock;
    out.push_str(include_str!("room_submit.rs.in"));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_submission_projection_uses_the_application_spelling_and_receipt_version() {
        let prepare = serde_json::from_value(serde_json::json!({
            "contract":"urn:gauge:room", "configuration":"gauge.json", "maximum_config_bytes":512,
            "operation":"reserve", "request":["action","station","routes"],
            "reply":["valid","reading","problem","work","phase","room","node","reason","receipt"],
            "states":["pending","reserved","refused"], "categories":["grant","route","unknown","capacity","offline"],
            "config_fields":["mode","grants","routes","protocol"], "roles":["collect","store"],
            "name_prefix":"reading-", "description":"Retained gauge room", "deadline_ms":150, "slot_limit":2
        })).unwrap();
        let submit = serde_json::from_value(serde_json::json!({
            "contract":"urn:gauge:record","operation":"record",
            "request":["action","station","routes","room","ticket","sample"],
            "payload":["measurements","capture","opaque"],
            "handle":["revision","gauge","station","room","capture","checksum"],
            "handle_field":"receipt","queued":"committed","accepted_ok":true,"refused_ok":false,
            "handle_format":7,"failures":["invalid","unreserved","ticket_taken","capture_taken","journal"],
            "max_future_seconds":30,"id_clock":"unix_seconds_u48be"
        })).unwrap();
        let binding = serde_json::from_value(serde_json::json!({
            "queue":["readings"],"request_type":["wire","Sample"],
            "encode":["wire","encode_sample"],
            "fields":["node","station","room","ticket","capture","measurements","opaque"]
        }))
        .unwrap();
        let mut source = String::new();
        render_room_submit(&mut source, &prepare, &submit, &binding);
        syn::parse_file(&source).unwrap();
        for expected in [
            "#[serde(rename = \"action\")]\n    operation: String,",
            "#[serde(rename = \"work\")]\n    command: T,",
            "#[serde(rename = \"receipt\")]\n    handle: SubmitHandle,",
            "#[serde(rename = \"checksum\")]\n    digest: String,",
            "const SUBMIT_QUEUED: &str = \"committed\";",
            "const SUBMIT_ACCEPTED_OK: bool = true;",
            "const SUBMIT_REFUSED_OK: bool = false;",
            "const SUBMIT_HANDLE_FORMAT: u8 = 7;",
            "measurements: chunks,",
        ] {
            assert!(source.contains(expected), "missing {expected}");
        }
    }
}
