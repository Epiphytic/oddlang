use super::*;
use std::{collections::BTreeSet, fmt::Write};

pub(super) fn render(graph: &Graph, binding: &Binding) -> Result<String, String> {
    if graph.profile != "command-surface-v1"
        || graph.package_name.is_empty()
        || graph.version.is_empty()
        || binding.executable.is_empty()
        || graph.root.name != graph.package_name
        || binding.invalid_exit == 0
        || binding.uncovered_exit == 0
    {
        return Err("invalid command graph or process metadata".into());
    }
    if binding
        .invalid_diagnostic
        .as_ref()
        .is_some_and(|message| message.chars().any(char::is_control))
    {
        return Err("invalid process diagnostic".into());
    }
    let mut operations = BTreeSet::from([String::new()]);
    if graph.external {
        operations.insert("*".into());
    }
    validate(&graph.root, "", &BTreeSet::new(), &mut operations, 0)?;
    for (command, operation) in &binding.operations {
        if !operations.contains(command)
            || !operation.starts_with("urn:")
            || operation.chars().any(char::is_whitespace)
        {
            return Err(format!("invalid operation binding for {command:?}"));
        }
    }
    let mut out = String::from(
        "// Generated by Oddlang from command-surface-v1.\n\
         use clap::{Arg, ArgAction, ArgGroup, ArgMatches, Command, Error};\n\
         use std::{ffi::OsString, process::ExitCode};\n\n\
         pub enum Invocation {\n\
         \x20   Dispatch { operation: &'static str, matches: ArgMatches },\n\
         \x20   Uncovered(ArgMatches),\n\
         \x20   Terminal(Error),\n\
         }\n\n\
         fn command() -> Command {\n",
    );
    let mut root = render_command(&graph.root);
    write!(
        root,
        ".version({:?}).bin_name({:?})",
        graph.version, binding.executable
    )
    .unwrap();
    if graph.external {
        root.push_str(".allow_external_subcommands(true)");
    }
    writeln!(out, "    {root}\n}}").unwrap();
    out.push_str(
        "\npub fn parse(args: impl IntoIterator<Item = OsString>) -> Invocation {\n\
         \x20   let matches = match command().try_get_matches_from(args) {\n\
         \x20       Ok(matches) => matches,\n\
         \x20       Err(error) => return Invocation::Terminal(error),\n\
         \x20   };\n\
         \x20   let mut selected = &matches;\n\
         \x20   let mut path = String::new();\n\
         \x20   while let Some((name, child)) = selected.subcommand() {\n\
         \x20       if !path.is_empty() { path.push('/'); }\n\
         \x20       path.push_str(name);\n\
         \x20       selected = child;\n\
         \x20   }\n\
         \x20   match path.as_str() {\n",
    );
    for (path, operation) in &binding.operations {
        if path != "*" {
            writeln!(
                out,
                "        {path:?} => Invocation::Dispatch {{ operation: {operation:?}, matches }},"
            )
            .unwrap();
        }
    }
    if let Some(operation) = binding.operations.get("*") {
        let commands = graph
            .root
            .subcommands
            .iter()
            .map(|command| command.name.as_str())
            .collect::<Vec<_>>();
        writeln!(out, "        name if !name.is_empty() && !{commands:?}.contains(&name) => Invocation::Dispatch {{ operation: {operation:?}, matches }},").unwrap();
    }
    out.push_str("        _ => Invocation::Uncovered(matches),\n    }\n}\n");
    out.push_str(
        "\npub fn run_cli_with(handler: impl FnOnce(&'static str, ArgMatches) -> ExitCode) -> ExitCode {\n\
         \x20   match parse(std::env::args_os()) {\n\
         \x20       Invocation::Dispatch { operation, matches } => handler(operation, matches),\n\
         \x20       Invocation::Terminal(error) => {\n\
         \x20           let invalid = error.use_stderr();\n\
         \x20           let _ = error.print();\n\
         \x20           if invalid {\n",
    );
    if let Some(diagnostic) = &binding.invalid_diagnostic {
        writeln!(out, "                eprintln!(\"{{}}\", {diagnostic:?});").unwrap();
    }
    writeln!(
        out,
        "                ExitCode::from({})",
        binding.invalid_exit
    )
    .unwrap();
    out.push_str(
        "            } else {\n\
         \x20               ExitCode::SUCCESS\n\
         \x20           }\n\
         \x20       }\n\
         \x20       Invocation::Uncovered(_) => uncovered(),\n\
         \x20   }\n\
         }\n\n\
         pub fn run_cli() -> ExitCode {\n\
         \x20   run_cli_with(|_, _| uncovered())\n\
         }\n\n\
         fn uncovered() -> ExitCode {\n\
         \x20   eprintln!(\"command operation unavailable\");\n",
    );
    writeln!(out, "    ExitCode::from({})\n}}", binding.uncovered_exit).unwrap();
    Ok(out)
}

fn valid_name(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('-')
        && value
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_'))
}

fn validate(
    command: &Command,
    path: &str,
    inherited: &BTreeSet<String>,
    operations: &mut BTreeSet<String>,
    depth: usize,
) -> Result<(), String> {
    if depth > 16 || !valid_name(&command.name) {
        return Err(format!("invalid command name or depth at {path:?}"));
    }
    let mut ids = inherited.clone();
    let mut long_names = BTreeSet::from(["help"]);
    let mut short_names = BTreeSet::from(['h']);
    if depth == 0 {
        long_names.insert("version");
        short_names.insert('V');
    }
    for arg in &command.arguments {
        if !valid_name(&arg.id) || !ids.insert(arg.id.clone()) {
            return Err(format!("invalid or duplicate argument {}", arg.id));
        }
        let positional = arg.long.is_none() && arg.short.is_none();
        if arg
            .long
            .iter()
            .chain(&arg.aliases)
            .chain(&arg.visible_aliases)
            .any(|name| !valid_name(name) || !long_names.insert(name))
            || arg
                .short
                .is_some_and(|ch| !ch.is_ascii_alphanumeric() || !short_names.insert(ch))
            || (arg.last && !positional)
            || (arg.global && (positional || arg.required))
            || (arg.kind.is_none() && (positional || arg.repeated))
            || arg.bounds.as_ref().is_some_and(|bounds| {
                !matches!(arg.kind, Some(ValueKind::U64))
                    || bounds.maximum.is_some_and(|max| max < bounds.minimum)
            })
            || (!arg.possible_values.is_empty() && !matches!(arg.kind, Some(ValueKind::String)))
        {
            return Err(format!("invalid argument settings for {}", arg.id));
        }
    }
    let members = ids.clone();
    for group in &command.groups {
        if !valid_name(&group.id)
            || !ids.insert(group.id.clone())
            || group.arguments.is_empty()
            || group
                .arguments
                .iter()
                .any(|member| !members.contains(member))
        {
            return Err(format!("invalid group {}", group.id));
        }
    }
    for arg in &command.arguments {
        if arg
            .conflicts
            .iter()
            .chain(&arg.requires)
            .any(|target| target == &arg.id || !ids.contains(target))
        {
            return Err(format!("invalid argument relationship for {}", arg.id));
        }
    }
    let globals = inherited
        .iter()
        .cloned()
        .chain(
            command
                .arguments
                .iter()
                .filter(|arg| arg.global)
                .map(|arg| arg.id.clone()),
        )
        .collect();
    let mut names = BTreeSet::from(["help"]);
    for child in &command.subcommands {
        if std::iter::once(&child.name)
            .chain(&child.aliases)
            .chain(&child.visible_aliases)
            .any(|name| !valid_name(name) || !names.insert(name))
        {
            return Err(format!("invalid or duplicate subcommand {}", child.name));
        }
        let path = if path.is_empty() {
            child.name.clone()
        } else {
            format!("{path}/{}", child.name)
        };
        operations.insert(path.clone());
        validate(child, &path, &globals, operations, depth + 1)?;
    }
    Ok(())
}

fn render_command(command: &Command) -> String {
    let mut out = format!("Command::new({:?})", command.name);
    if let Some(help) = &command.help {
        write!(out, ".about({help:?})").unwrap();
    }
    if command.hidden {
        out.push_str(".hide(true)");
    }
    if command.subcommand_required {
        out.push_str(".subcommand_required(true).arg_required_else_help(true)");
    }
    for alias in &command.aliases {
        write!(out, ".alias({alias:?})").unwrap();
    }
    for alias in &command.visible_aliases {
        write!(out, ".visible_alias({alias:?})").unwrap();
    }
    for argument in &command.arguments {
        write!(out, ".arg({})", render_argument(argument)).unwrap();
    }
    for group in &command.groups {
        write!(
            out,
            ".group(ArgGroup::new({:?}).required({}).multiple({}).args({:?}))",
            group.id, group.required, group.multiple, group.arguments,
        )
        .unwrap();
    }
    for child in &command.subcommands {
        write!(out, ".subcommand({})", render_command(child)).unwrap();
    }
    out
}

fn render_argument(arg: &Argument) -> String {
    let mut out = format!("Arg::new({:?})", arg.id);
    if let Some(help) = &arg.help {
        write!(out, ".help({help:?})").unwrap();
    }
    if let Some(long) = &arg.long {
        write!(out, ".long({long:?})").unwrap();
    }
    if let Some(short) = arg.short {
        write!(out, ".short({short:?})").unwrap();
    }
    let positional = arg.long.is_none() && arg.short.is_none();
    if let Some(kind) = arg.kind {
        write!(out, ".value_name({:?})", arg.value_name).unwrap();
        if arg.repeated {
            out.push_str(".action(ArgAction::Append)");
            if positional {
                out.push_str(".num_args(1..)");
            }
        } else {
            out.push_str(".action(ArgAction::Set)");
        }
        if !arg.possible_values.is_empty() {
            write!(out, ".value_parser({:?})", arg.possible_values).unwrap();
        } else {
            let ty = match kind {
                ValueKind::String => "String",
                ValueKind::OsString => "std::ffi::OsString",
                ValueKind::Path => "std::path::PathBuf",
                ValueKind::U32 => "u32",
                ValueKind::U64 => "u64",
                ValueKind::Usize => "usize",
            };
            write!(out, ".value_parser(clap::value_parser!({ty})").unwrap();
            if let Some(bounds) = &arg.bounds {
                match bounds.maximum {
                    Some(max) => write!(out, ".range({}..={max})", bounds.minimum).unwrap(),
                    None => write!(out, ".range({}..)", bounds.minimum).unwrap(),
                }
            }
            out.push(')');
        }
    } else {
        out.push_str(".action(ArgAction::SetTrue)");
    }
    if let Some(default) = &arg.default_value {
        write!(out, ".default_value({default:?})").unwrap();
    }
    if arg.required {
        out.push_str(".required(true)");
    }
    if arg.global {
        out.push_str(".global(true)");
    }
    if arg.last {
        out.push_str(".last(true)");
    }
    for alias in &arg.aliases {
        write!(out, ".alias({alias:?})").unwrap();
    }
    for alias in &arg.visible_aliases {
        write!(out, ".visible_alias({alias:?})").unwrap();
    }
    for target in &arg.conflicts {
        write!(out, ".conflicts_with({target:?})").unwrap();
    }
    for target in &arg.requires {
        write!(out, ".requires({target:?})").unwrap();
    }
    out
}
