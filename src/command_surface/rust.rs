use super::*;
use std::{collections::BTreeSet, fmt::Write};

pub(super) fn render(graph: &Graph, binding: &Binding) -> Result<String, String> {
    if graph.profile != "command-surface-v1"
        || graph.package_name.is_empty()
        || graph.version.is_empty()
        || binding.executable.is_empty()
        || graph.root.name != graph.package_name
        || !valid_name(&graph.root.name)
        || binding.invalid_exit == 0
        || binding.uncovered_exit == 0
    {
        return Err("invalid command graph or process metadata".into());
    }
    if binding
        .invalid_diagnostic
        .as_ref()
        .is_some_and(|message| message.chars().any(char::is_control))
    {
        return Err("invalid process diagnostic".into());
    }
    let mut operations = BTreeSet::from([String::new()]);
    if graph.external {
        operations.insert("*".into());
    }
    validate(&graph.root, "", &[], &mut operations, 0)?;
    for (trigger, parser) in &graph.terminal_subparsers {
        let Some(child) = graph
            .root
            .subcommands
            .iter()
            .find(|child| &child.name == trigger)
        else {
            return Err(format!("unknown terminal parser trigger {trigger:?}"));
        };
        if !child.aliases.is_empty()
            || !child.visible_aliases.is_empty()
            || !child.subcommands.is_empty()
            || binding.operations.contains_key(trigger)
            || !parser.subcommands.is_empty()
            || parser.subcommand_required
            || parser.hidden
            || !parser.aliases.is_empty()
            || !parser.visible_aliases.is_empty()
            || parser.arguments.iter().any(|argument| argument.global)
            || !parser.name.split(' ').all(valid_name)
        {
            return Err(format!("invalid terminal parser for {trigger:?}"));
        }
        // The auxiliary parser has its own argument identities and no version flag.
        validate(parser, trigger, &[], &mut BTreeSet::new(), 1)?;
    }
    for (trigger, policy) in &graph.terminal_prefixes {
        let allowed: BTreeSet<_> = policy.allowed.iter().collect();
        if !graph.terminal_subparsers.contains_key(trigger)
            || allowed.len() != policy.allowed.len()
            || policy.denied.is_empty()
            || policy.denied.chars().any(char::is_control)
            || allowed.iter().any(|id| {
                !graph
                    .root
                    .arguments
                    .iter()
                    .any(|argument| argument.global && &argument.id == *id)
            })
        {
            return Err(format!("invalid terminal prefix policy for {trigger:?}"));
        }
    }
    for (command, operation) in &binding.operations {
        if !operations.contains(command)
            || !operation.starts_with("urn:")
            || operation.chars().any(char::is_whitespace)
        {
            return Err(format!("invalid operation binding for {command:?}"));
        }
    }
    for (operation, path) in &binding.handlers {
        if !binding.operations.values().any(|id| id == operation)
            || path.is_empty()
            || path.iter().any(|identifier| {
                identifier == "gen" || syn::parse_str::<syn::Ident>(identifier).is_err()
            })
        {
            return Err(format!("invalid native command handler for {operation:?}"));
        }
    }
    let mut out = String::from(
        "// Generated by Oddlang from command-surface-v1.\n\
         use clap::{Arg, ArgAction, ArgGroup, ArgMatches, Command, Error};\n\
         use std::{ffi::OsString, process::ExitCode};\n\n\
         pub enum Invocation {\n\
         \x20   Dispatch { operation: &'static str, matches: ArgMatches },\n\
         \x20   Uncovered,\n\
         \x20   Terminal(Error),\n\
         }\n\n\
         fn command() -> Command {\n",
    );
    let mut root = render_command(&graph.root);
    write!(
        root,
        ".version({:?}).bin_name({:?})",
        graph.version, binding.executable
    )
    .unwrap();
    if graph.external {
        root.push_str(".allow_external_subcommands(true)");
    }
    writeln!(out, "    {root}\n}}").unwrap();
    if !graph.terminal_prefixes.is_empty() {
        out.push_str(include_str!("terminal_prefix.rs"));
    }
    out.push_str("\npub fn parse(args: impl IntoIterator<Item = OsString>) -> Invocation {\n");
    if !graph.terminal_prefixes.is_empty() {
        out.push_str("    let args = args.into_iter().collect::<Vec<_>>();\n");
        let globals = graph
            .root
            .arguments
            .iter()
            .filter(|argument| argument.global)
            .map(|argument| {
                (
                    argument.id.as_str(),
                    argument.long.as_deref(),
                    argument.short.map(|byte| byte as u8),
                    argument.kind.is_some(),
                    argument.allow_hyphen_values,
                )
            })
            .collect::<Vec<_>>();
        for (trigger, policy) in &graph.terminal_prefixes {
            let auxiliary = render_command(&graph.terminal_subparsers[trigger]);
            writeln!(out, "    if let Some(result) = terminal_prefix(&args, {trigger:?}, &{globals:?}, &{:?}, {:?}, {auxiliary}) {{ return result; }}", policy.allowed, policy.denied).unwrap();
        }
    }

    if !graph.terminal_subparsers.is_empty() {
        out.push_str(
            "    let mut args = args.into_iter().peekable();\n    let executable = args.next();\n",
        );
        for (trigger, parser) in &graph.terminal_subparsers {
            let rendered = render_command(parser);
            writeln!(
                out,
                "    if args.peek().is_some_and(|name| name == {trigger:?}) {{"
            )
            .unwrap();
            out.push_str("        args.next();\n");
            writeln!(
                out,
                "        let args = std::iter::once(OsString::from({:?})).chain(args);",
                parser.name
            )
            .unwrap();
            writeln!(
                out,
                "        return match {rendered}.try_get_matches_from(args) {{"
            )
            .unwrap();
            out.push_str("            Ok(_) => Invocation::Uncovered,\n            Err(error) => Invocation::Terminal(error),\n        };\n    }\n");
        }
        out.push_str("    let args = executable.into_iter().chain(args);\n");
    }
    out.push_str(
        "    let matches = match command().try_get_matches_from(args) {\n\
         \x20       Ok(matches) => matches,\n\
         \x20       Err(error) => return Invocation::Terminal(error),\n\
         \x20   };\n",
    );
    if graph.external {
        let commands = graph
            .root
            .subcommands
            .iter()
            .map(|command| command.name.as_str())
            .collect::<Vec<_>>();
        writeln!(
            out,
            "    if matches.subcommand_name().is_some_and(|name| !{commands:?}.contains(&name)) {{"
        )
        .unwrap();
        if let Some(operation) = binding.operations.get("*") {
            writeln!(
                out,
                "        return Invocation::Dispatch {{ operation: {operation:?}, matches }};"
            )
            .unwrap();
        } else {
            out.push_str("        return Invocation::Uncovered;\n");
        }
        out.push_str("    }\n");
    }
    out.push_str(
        "    let mut selected = &matches;\n\
         \x20   let mut path = String::new();\n\
         \x20   while let Some((name, child)) = selected.subcommand() {\n\
         \x20       if !path.is_empty() { path.push('/'); }\n\
         \x20       path.push_str(name);\n\
         \x20       selected = child;\n\
         \x20   }\n\
         \x20   match path.as_str() {\n",
    );
    for (path, operation) in &binding.operations {
        if path != "*" {
            writeln!(
                out,
                "        {path:?} => Invocation::Dispatch {{ operation: {operation:?}, matches }},"
            )
            .unwrap();
        }
    }
    out.push_str("        _ => Invocation::Uncovered,\n    }\n}\n");
    out.push_str(
        "\npub fn run_cli_with(handler: impl FnOnce(&'static str, ArgMatches) -> ExitCode) -> ExitCode {\n\
         \x20   match parse(std::env::args_os()) {\n\
         \x20       Invocation::Dispatch { operation, matches } => handler(operation, matches),\n\
         \x20       Invocation::Terminal(error) => {\n\
         \x20           let invalid = error.use_stderr();\n\
         \x20           let _ = error.print();\n\
         \x20           if invalid {\n",
    );
    if let Some(diagnostic) = &binding.invalid_diagnostic {
        writeln!(out, "                eprintln!(\"{{}}\", {diagnostic:?});").unwrap();
    }
    writeln!(
        out,
        "                ExitCode::from({})",
        binding.invalid_exit
    )
    .unwrap();
    out.push_str(
        "            } else {\n\
         \x20               ExitCode::SUCCESS\n\
         \x20           }\n\
         \x20       }\n\
         \x20       Invocation::Uncovered => uncovered(),\n\
         \x20   }\n\
         }\n\n\
         pub fn run_cli() -> ExitCode {\n",
    );
    if binding.handlers.is_empty() {
        out.push_str("    run_cli_with(|_, _| uncovered())\n");
    } else {
        out.push_str("    run_cli_with(|operation, matches| match operation {\n");
        for (operation, path) in &binding.handlers {
            writeln!(
                out,
                "        {operation:?} => crate::{}(matches),",
                path.join("::")
            )
            .unwrap();
        }
        out.push_str("        _ => uncovered(),\n    })\n");
    }
    out.push_str(
        "}\n\n\
         fn uncovered() -> ExitCode {\n\
         \x20   eprintln!(\"command operation unavailable\");\n",
    );
    writeln!(out, "    ExitCode::from({})\n}}", binding.uncovered_exit).unwrap();
    Ok(out)
}

fn valid_name(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('-')
        && value
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_'))
}

fn validate<'a>(
    command: &'a Command,
    path: &str,
    inherited: &[&'a Argument],
    operations: &mut BTreeSet<String>,
    depth: usize,
) -> Result<(), String> {
    if depth > 16 {
        return Err(format!("invalid command name or depth at {path:?}"));
    }
    let mut ids = BTreeSet::from(["help".to_owned()]);
    let mut long_names = BTreeSet::from(["help"]);
    let mut short_names = BTreeSet::from(['h']);
    if depth == 0 {
        ids.insert("version".to_owned());
        long_names.insert("version");
        short_names.insert('V');
    }
    for arg in inherited.iter().copied().chain(&command.arguments) {
        if !valid_name(&arg.id) || !ids.insert(arg.id.clone()) {
            return Err(format!("invalid or duplicate argument {}", arg.id));
        }
        let positional = arg.long.is_none() && arg.short.is_none();
        if arg
            .long
            .iter()
            .chain(&arg.aliases)
            .chain(&arg.visible_aliases)
            .any(|name| !valid_name(name) || !long_names.insert(name))
            || arg
                .short
                .is_some_and(|ch| !ch.is_ascii_alphanumeric() || !short_names.insert(ch))
            || (arg.last && !positional)
            || (arg.trailing_var_arg && (!positional || !arg.repeated || arg.last))
            || (arg.allow_hyphen_values && arg.kind.is_none())
            || (arg.global && (positional || arg.required))
            || (arg.kind.is_none() && (positional || arg.repeated))
            || arg.bounds.as_ref().is_some_and(|bounds| {
                !matches!(arg.kind, Some(ValueKind::U64))
                    || bounds.maximum.is_some_and(|max| max < bounds.minimum)
            })
            || (!arg.possible_values.is_empty() && !matches!(arg.kind, Some(ValueKind::String)))
            || arg
                .default_value
                .as_ref()
                .is_some_and(|value| !valid_default(arg, value))
        {
            return Err(format!("invalid argument settings for {}", arg.id));
        }
    }
    validate_positionals(command)?;
    let members = ids.clone();
    for group in &command.groups {
        if !valid_name(&group.id)
            || !ids.insert(group.id.clone())
            || group.arguments.is_empty()
            || group
                .arguments
                .iter()
                .any(|member| !members.contains(member))
        {
            return Err(format!("invalid group {}", group.id));
        }
    }
    for arg in inherited.iter().copied().chain(&command.arguments) {
        if arg
            .conflicts
            .iter()
            .chain(&arg.requires)
            .any(|target| target == &arg.id || !ids.contains(target))
        {
            return Err(format!("invalid argument relationship for {}", arg.id));
        }
    }
    let globals = inherited
        .iter()
        .copied()
        .chain(command.arguments.iter().filter(|arg| arg.global))
        .collect::<Vec<_>>();
    let mut names = BTreeSet::from(["help"]);
    for child in &command.subcommands {
        if std::iter::once(&child.name)
            .chain(&child.aliases)
            .chain(&child.visible_aliases)
            .any(|name| !valid_name(name) || !names.insert(name))
        {
            return Err(format!("invalid or duplicate subcommand {}", child.name));
        }
        let path = if path.is_empty() {
            child.name.clone()
        } else {
            format!("{path}/{}", child.name)
        };
        operations.insert(path.clone());
        validate(child, &path, &globals, operations, depth + 1)?;
    }
    Ok(())
}

fn valid_default(arg: &Argument, value: &str) -> bool {
    if arg.required {
        return false;
    }
    match arg.kind {
        None => false,
        Some(ValueKind::String) => {
            arg.possible_values.is_empty()
                || arg.possible_values.iter().any(|possible| possible == value)
        }
        Some(ValueKind::U32) => value.parse::<u32>().is_ok(),
        Some(ValueKind::Usize) => value.parse::<usize>().is_ok(),
        Some(ValueKind::U64) => value.parse::<u64>().is_ok_and(|value| {
            arg.bounds.as_ref().is_none_or(|bounds| {
                value >= bounds.minimum && bounds.maximum.is_none_or(|maximum| value <= maximum)
            })
        }),
        Some(ValueKind::OsString | ValueKind::Path) => true,
    }
}

fn validate_positionals(command: &Command) -> Result<(), String> {
    let args = command
        .arguments
        .iter()
        .filter(|arg| arg.long.is_none() && arg.short.is_none())
        .collect::<Vec<_>>();
    let mut seen_optional = false;
    for (index, arg) in args.iter().enumerate() {
        let next = args.get(index + 1);
        let invalid_last =
            arg.last && (next.is_some() || (arg.required && !command.subcommands.is_empty()));
        let invalid_repeated = arg.repeated
            && next.is_some_and(|next| {
                index + 2 != args.len()
                    || (!next.required && !next.last)
                    || (next.repeated && !next.last)
            });
        let invalid_required = arg.required && seen_optional && !arg.last;
        if invalid_last
            || invalid_repeated
            || invalid_required
            || (arg.trailing_var_arg && next.is_some())
        {
            return Err(format!(
                "ambiguous placement of positional argument {}",
                arg.id
            ));
        }
        seen_optional |= !arg.required;
    }
    Ok(())
}

fn render_command(command: &Command) -> String {
    let mut out = format!("Command::new({:?})", command.name);
    if let Some(help) = &command.help {
        write!(out, ".about({help:?})").unwrap();
    }
    if command.hidden {
        out.push_str(".hide(true)");
    }
    if command.subcommand_required {
        out.push_str(".subcommand_required(true).arg_required_else_help(true)");
    }
    for alias in &command.aliases {
        write!(out, ".alias({alias:?})").unwrap();
    }
    for alias in &command.visible_aliases {
        write!(out, ".visible_alias({alias:?})").unwrap();
    }
    for argument in &command.arguments {
        write!(out, ".arg({})", render_argument(argument)).unwrap();
    }
    for group in &command.groups {
        write!(
            out,
            ".group(ArgGroup::new({:?}).required({}).multiple({}).args({:?}))",
            group.id, group.required, group.multiple, group.arguments,
        )
        .unwrap();
    }
    for child in &command.subcommands {
        write!(out, ".subcommand({})", render_command(child)).unwrap();
    }
    out
}

fn render_argument(arg: &Argument) -> String {
    let mut out = format!("Arg::new({:?})", arg.id);
    if let Some(help) = &arg.help {
        write!(out, ".help({help:?})").unwrap();
    }
    if let Some(long) = &arg.long {
        write!(out, ".long({long:?})").unwrap();
    }
    if let Some(short) = arg.short {
        write!(out, ".short({short:?})").unwrap();
    }
    let positional = arg.long.is_none() && arg.short.is_none();
    if let Some(kind) = arg.kind {
        write!(out, ".value_name({:?})", arg.value_name).unwrap();
        if arg.repeated {
            out.push_str(".action(ArgAction::Append)");
            if positional {
                out.push_str(".num_args(1..)");
            }
        } else {
            out.push_str(".action(ArgAction::Set)");
        }
        if !arg.possible_values.is_empty() {
            write!(out, ".value_parser({:?})", arg.possible_values).unwrap();
        } else {
            let ty = match kind {
                ValueKind::String => "String",
                ValueKind::OsString => "std::ffi::OsString",
                ValueKind::Path => "std::path::PathBuf",
                ValueKind::U32 => "u32",
                ValueKind::U64 => "u64",
                ValueKind::Usize => "usize",
            };
            write!(out, ".value_parser(clap::value_parser!({ty})").unwrap();
            if let Some(bounds) = &arg.bounds {
                match bounds.maximum {
                    Some(max) => write!(out, ".range({}..={max})", bounds.minimum).unwrap(),
                    None => write!(out, ".range({}..)", bounds.minimum).unwrap(),
                }
            }
            out.push(')');
        }
    } else {
        out.push_str(".action(ArgAction::SetTrue)");
    }
    if let Some(default) = &arg.default_value {
        write!(out, ".default_value({default:?})").unwrap();
    }
    if arg.required {
        out.push_str(".required(true)");
    }
    if arg.global {
        out.push_str(".global(true)");
    }
    if arg.last {
        out.push_str(".last(true)");
    }
    if arg.trailing_var_arg {
        out.push_str(".trailing_var_arg(true)");
    }
    if arg.allow_hyphen_values {
        out.push_str(".allow_hyphen_values(true)");
    }
    for alias in &arg.aliases {
        write!(out, ".alias({alias:?})").unwrap();
    }
    for alias in &arg.visible_aliases {
        write!(out, ".visible_alias({alias:?})").unwrap();
    }
    for target in &arg.conflicts {
        write!(out, ".conflicts_with({target:?})").unwrap();
    }
    for target in &arg.requires {
        write!(out, ".requires({target:?})").unwrap();
    }
    out
}
